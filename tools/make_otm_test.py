#!/usr/bin/env python3
"""[I] tools/make_otm.py against the linker: `make otm-test` (needs the ARM
toolchain and pyelftools).

Builds a small module eight times, with 0..7 bytes of extra read-only data so
the code + data ends at every offset modulo 8, each with --reference. For
each: the image is a multiple of 8 B (the bss starts right after it), and an
otmLoad done here (image, zeroed bss, fixups) gives the bytes the linker placed
at the reference base, bss included.

  make_otm_test.py --cxx CXX --cxxflags "FLAGS"
"""
import argparse
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
MAKE_OTM = os.path.join(HERE, "make_otm.py")
BASE = 0x1FFF8000
HDR = "<IHHII8sIIIIII"

SOURCE = """// Generated by tools/make_otm_test.py.
namespace ot {{
namespace mod {{
class IModule;
extern const char kPad[{pad}];
const char kPad[{pad}] = {{{bytes}}};   // read-only data that ends the image
int gCount[3];   // bss: written by the entry
IModule& gap() {{
    gCount[2] += int(reinterpret_cast<unsigned long>(&kPad[{last}]));   // a fixup into the data
    return *reinterpret_cast<IModule*>(gCount);
}}
}}  // namespace mod
}}  // namespace ot
"""


def fake_export(k):
    return 0x0E000000 + 16 * k + 1   # make_otm.py fake_export


def load(otm):
    """What otmLoad writes at BASE (module_loader.cpp), with the fake exports."""
    (magic, hb, api, layout, abi, mid, nimg, nbss, align, entry, nfix, nexp) = struct.unpack_from(HDR, otm)
    img = bytearray(otm[hb:hb + nimg]) + bytearray(nbss)
    fix = otm[hb + nimg:hb + nimg + 4 * nfix]
    for i in range(nfix):
        (f,) = struct.unpack_from("<I", fix, 4 * i)
        off, kind = f & 0xFFFFFF, f >> 24
        (w,) = struct.unpack_from("<I", img, off)
        struct.pack_into("<I", img, off, (w + (fake_export(kind) if kind else BASE)) & 0xFFFFFFFF)
    return bytes(img), nimg, nbss


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--cxx", required=True)
    p.add_argument("--cxxflags", required=True)
    args = p.parse_args()
    failed = 0
    with tempfile.TemporaryDirectory() as tmp:
        for extra in range(8):
            pad = 1 + extra
            mdir = os.path.join(tmp, f"gap{extra}")
            os.makedirs(os.path.join(mdir, "src"))
            with open(os.path.join(mdir, "module.toml"), "w") as f:
                f.write('id = "GAP0"\napi = 1\nentry = "gap"\nsources = ["gap.cpp"]\n')
            with open(os.path.join(mdir, "src", "gap.cpp"), "w") as f:
                f.write(SOURCE.format(pad=pad, bytes=", ".join(str(i + 1) for i in range(pad)), last=pad - 1))
            out, ref = os.path.join(mdir, "gap.otm"), os.path.join(mdir, "gap.ref.bin")
            r = subprocess.run([sys.executable, "-I", MAKE_OTM, "build", "--module", mdir,
                                "--obj-dir", os.path.join(mdir, "obj"), "--out", out, "--cxx", args.cxx,
                                "--cxxflags", args.cxxflags, "--reference", hex(BASE), "--ref-out", ref],
                               capture_output=True, text=True)
            if r.returncode != 0:
                print(f"FAIL +{extra} B: make_otm.py build failed:\n{r.stderr}")
                failed += 1
                continue
            got, nimg, nbss = load(open(out, "rb").read())
            want = open(ref, "rb").read()
            if nimg % 8:
                print(f"FAIL +{extra} B: image {nimg} B is not a multiple of 8 (bss would start in a gap)")
                failed += 1
            elif got != want:
                print(f"FAIL +{extra} B: loaded {len(got)} B (image {nimg} + bss {nbss}) != linker {len(want)} B")
                failed += 1
    print(f"make_otm_test: {8 - failed} of 8 builds match the linker")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
