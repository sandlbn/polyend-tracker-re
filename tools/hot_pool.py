class Image:
    def __init__(self, path):
        ELFFile, self.RelocationSection = make_otm.elftools()
        self.f = open(path, "rb")
        self.elf = ELFFile(self.f)
        self.secs = [s for s in self.elf.iter_sections() if s["sh_flags"] & SHF_ALLOC and s["sh_type"] != "SHT_NOBITS"]
        st = self.elf.get_section_by_name(".symtab")
        self.syms = list(st.iter_symbols())
        self.by_name = {s.name: s for s in self.syms}
        self.objects = sorted((s["st_value"], s["st_size"], s.name) for s in self.syms
                              if s["st_info"]["type"] == "STT_OBJECT" and s["st_size"] and s["st_value"] < FLASH_END)
        self.funcs = sorted((s["st_value"] & ~1, s["st_size"], s.name) for s in self.syms
                            if s["st_info"]["type"] == "STT_FUNC" and s["st_size"])
        self.rels = []   # (address, type, value read there)
        for rs in self.elf.iter_sections():
            if not isinstance(rs, self.RelocationSection) or ".debug" in rs.name:
                continue
            target = self.elf.get_section(rs["sh_info"])
            if not target["sh_flags"] & SHF_ALLOC or target["sh_type"] == "SHT_NOBITS":
                continue
            for r in rs.iter_relocations():
                self.rels.append((r["r_offset"], r["r_info_type"], target))

    def sym(self, name):
        s = self.by_name.get(name)
        if s is None:
            fail(f"{name} missing from the image")
        return s["st_value"]

    def word(self, addr):
        for s in self.secs:
            if s["sh_addr"] <= addr < s["sh_addr"] + s["sh_size"]:
                off = addr - s["sh_addr"]
                return int.from_bytes(s.data()[off:off + 4], "little")
        fail(f"no contents at {addr:#x}")

    def object_at(self, addr):
        for a, n, name in self.objects:
            if a <= addr < a + n:
                return a, n, name
        return None

    def func_at(self, addr):
        for a, n, name in self.funcs:
            if a <= addr < a + n:
                return name
        return f"{addr:#x}"


def row_table(img, name, entry):
    start, end = img.sym(f"__hotrow_{name}_start"), img.sym(f"__hotrow_{name}_end")
    if end <= start:
        return None
    cuts, k = [], 0
    while f"__hotrow_{name}_cut_{k}" in img.by_name:
        cuts.append(img.sym(f"__hotrow_{name}_cut_{k}") - start)
        k += 1
    # Empty pieces (a function the link dropped) leave repeated cuts.
    cuts = sorted(set(c for c in cuts if c > 0))
    if start & 7 or not cuts or cuts[-1] != end - start:
        fail(f"{name}: row at {start:#x}..{end:#x} has bad cuts")
    in_row = lambda a: start <= (a & ~1) < end   # noqa: E731
    fixups, words = [], []   # words: (row offset, value) of ABS32 in the row
    for at, t, sec in img.rels:
        if not start <= at < end or t == R_ARM_NONE:
            continue
        if t in (R_ARM_THM_CALL, R_ARM_THM_JUMP24):
            fixups.append((at - start) | KIND_BRANCH << 24)
        elif t == R_ARM_ABS32:
            words.append((at - start, img.word(at)))
        else:
            fail(f"{name}: relocation type {t} at {at:#x} ({img.func_at(at)})")
    # Tables: flash objects with words pointing into the row.
    tables = {}   # address -> (size, name, [entry offsets])
    leaks = {}
    for at, t, sec in img.rels:
        if t != R_ARM_ABS32 or start <= at < end:
            continue
        v = img.word(at)
        if not in_row(v):
            continue
        if at >= FLASH_END:
            fail(f"{name}: RAM word at {at:#x} points into the row ({img.func_at(v)}): "
                 "a mutable function pointer can't follow a move")
        obj = img.object_at(at)   # a constant table; else a literal in flash code
        if obj:
            a, n, oname = obj
            tables.setdefault(a, (n, oname, []))[2].append(at - a)
        else:
            leaks[img.func_at(at)] = leaks.get(img.func_at(at), 0) + 1
    for at, t, sec in img.rels:   # direct calls from flash outside the row
        if t in (R_ARM_THM_CALL, R_ARM_THM_JUMP24) and not start <= at < end and at < FLASH_END:
            d = make_otm.branch_offset(_bytes(img, at), 0)
            if d is not None and in_row(at + 4 + d):
                leaks[img.func_at(at)] = leaks.get(img.func_at(at), 0) + 1
    # Slots: RAM words pointing into a table; tables the moved code or a
    # slot reaches (others stay in flash: reached from flash only).
    slots, used = [], set()
    for at, t, sec in img.rels:
        if t != R_ARM_ABS32 or at < FLASH_END:
            continue
        v = img.word(at)
        for a, (n, _, _) in tables.items():
            if a <= v < a + n:
                slots.append((at, v))
                used.add(a)
    for off, v in words:
        for a, (n, _, _) in tables.items():
            if a <= v < a + n:
                used.add(a)
    for a in sorted(set(tables) - used):
        n, oname, _ = tables.pop(a)
        leaks[oname] = leaks.get(oname, 0) + 1
    relevant = lambda v: in_row(v) or any(a <= v < a + n for a, (n, _, _) in tables.items())  # noqa: E731
    fixups += [off | KIND_WORD << 24 for off, v in words if relevant(v)]
    return dict(name=name, entry=entry, start=start, bytes=end - start, cuts=cuts, fixups=sorted(fixups),
                tables=[(a, n, oname, sorted(es)) for a, (n, oname, es) in sorted(tables.items())],
                slots=sorted(slots), leaks=leaks)


def _bytes(img, addr):
    w0, w1 = img.word(addr & ~3), img.word((addr & ~3) + 4)
    raw = (w0 | w1 << 32).to_bytes(8, "little")
    return raw[addr & 3:(addr & 3) + 4]


def emit(rows):
    L = ["@ Generated by tools/hot_pool.py table -- do not edit.",
         "    .syntax unified", '    .section .ot_hot_rows,"a",%progbits', "    .balign 4",
         "    .global otHotRows", "otHotRows:", f"    .word {len(rows)}, {'hot_rows' if rows else 0}"]
    if rows:
        L.append("hot_rows:")
    for r in rows:
        n = r["name"]
        L.append(f"    .word {make_otm.mangle_entry(r['entry'])}, {r['start']:#x}, {r['start']:#x}, {r['bytes']}, "
                 f"{len(r['cuts'])}, hr_{n}_cuts, {len(r['fixups'])}, hr_{n}_fix, "
                 f"{len(r['tables'])}, {'hr_%s_tab' % n if r['tables'] else 0}, "
                 f"{len(r['slots'])}, {'hr_%s_slots' % n if r['slots'] else 0}")
    for r in rows:
        n = r["name"]
        L.append(f"hr_{n}_cuts: .word {', '.join(map(str, r['cuts']))}")
        L.append(f"hr_{n}_fix:" + ("".join(f"\n    .word {f:#x}" for f in r["fixups"]) or " .word 0"))
        if r["tables"]:
            L.append(f"hr_{n}_tab:")
            for i, (a, sz, oname, es) in enumerate(r["tables"]):
                L.append(f"    .word {a:#x}, {a:#x}, {sz}, {len(es)}, hr_{n}_t{i}   @ {oname}")
            for i, (a, sz, oname, es) in enumerate(r["tables"]):
                L.append(f"hr_{n}_t{i}: .word {', '.join(map(str, es))}")
        if r["slots"]:
            L.append(f"hr_{n}_slots:")
            for at, v in r["slots"]:
                L.append(f"    .word {at:#x}, {v:#x}")
    return "\n".join(L) + "\n"


def table(args):
    rows = []
    if args.elf:
        img = Image(args.elf)
        for name, entry in parse_rows(args.row, 2):
            r = row_table(img, name, entry)
            if r:
                rows.append(r)
                if not args.quiet:
                    nstub = len({f for f in r["fixups"] if f >> 24 == KIND_BRANCH})
                    print(f"hot_pool: {name}: row {r['bytes']} B in {len(r['cuts'])} cuts, "
                          f"{len(r['fixups'])} fixups ({nstub} branches), {len(r['tables'])} tables, "
                          f"{len(r['slots'])} slots")
                    for who, c in sorted(r["leaks"].items()):
                        print(f"hot_pool:   {name}: reached from flash only: {who} ({c})")
    text = emit(rows)
    old = open(args.out).read() if os.path.exists(args.out) else None
    if old != text:
        with open(args.out, "w") as f:
            f.write(text)
    if args.expect and open(args.expect).read() != text:
        fail(f"{args.out}: the second link changed the table (see {args.expect})")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("layout")
    a.add_argument("--out", required=True)
    a.add_argument("--row", action="append")
    t = sub.add_parser("table")
    t.add_argument("--elf")
    t.add_argument("--out", required=True)
    t.add_argument("--row", action="append")
    t.add_argument("--expect")
    t.add_argument("--quiet", action="store_true")
    args = p.parse_args()
    if len(args.row or []) > max_rows():
        fail(f"{len(args.row)} hot rows, the firmware takes {max_rows()} (OtmLoadReport::kMaxHot)")
    {"layout": layout, "table": table}[args.cmd](args)


if __name__ == "__main__":
    main()
