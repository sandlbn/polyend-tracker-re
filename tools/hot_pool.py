#!/usr/bin/env python3
"""[I] Built-in synths' hot rows for the shared fast pool
(src/core/modules/hot_rows.h).

  hot_pool.py layout --out FILE.ld [--row NAME:HOTFILE:OBJ[,OBJ...]]...
      Before the link: the linker script fragment that places each row's
      functions (tools/hot_rows/<name>.hot, hottest first) back to back in
      flash, each at a multiple of 8, with __hotrow_<name>_start, a
      __hotrow_<name>_cut_<k> after each piece and __hotrow_<name>_end.
      Functions in a COMDAT group (shared with other objects) or aligned to
      more than 8 stay out. A split function's header (GCC ipa-split: X
      calling X.part.N) goes right before its part: it is the way in.
  hot_pool.py table --elf ELF --out FILE.S [--row NAME:ENTRY]... [--quiet]
      After a link with --emit-relocs (-Wl,-q): the rows' fixups, tables and
      slots as the HotRows table otHotRows (section .ot_hot_rows, placed
      after all other flash contents, so its size moves nothing the table
      describes). The build links twice and checks that the second link
      gives the same table. Prints, per row, what still reaches it from
      flash only (it then runs the flash copy: slower, not wrong).

Refused: relocation types in a row other than R_ARM_ABS32 / R_ARM_THM_CALL /
R_ARM_THM_JUMP24 / R_ARM_NONE, a row the link did not keep, and RAM words
pointing straight into a row (mutable function pointers).
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_otm  # noqa: E402  (read_hot, clone_base, mangle_entry, elftools)

R_ARM_NONE, R_ARM_ABS32, R_ARM_THM_CALL, R_ARM_THM_JUMP24 = 0, 2, 10, 30
SHF_ALLOC, SHF_EXECINSTR, SHF_GROUP = 0x2, 0x4, 0x200
FLASH_END = 0x00100000
KIND_BRANCH, KIND_WORD = 1, 2


def fail(msg):
    print(f"hot_pool: {msg}", file=sys.stderr)
    sys.exit(1)


def max_rows():
    """OtmLoadReport::kMaxHot (src/core/modules/module_files.h): rows past it never move."""
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "core", "modules", "module_files.h")
    m = re.search(r"static constexpr int kMaxHot = (\d+);", open(path).read())
    if not m:
        fail(f"no kMaxHot in {path}")
    return int(m.group(1))


def parse_rows(specs, nparts):
    rows = []
    for s in specs or []:
        p = s.split(":")
        if len(p) != nparts:
            fail(f"bad --row {s!r}")
        rows.append(p)
    return rows


# ---- layout -------------------------------------------------------------------


def functions(objs):
    """name -> (object, section name, size, movable) for every function."""
    out = {}
    ELFFile, _ = make_otm.elftools()   # only with rows: a profile without any builds without pyelftools
    for o in objs:
        with open(o, "rb") as f:
            elf = ELFFile(f)
            for sym in elf.get_section_by_name(".symtab").iter_symbols():
                if sym["st_info"]["type"] != "STT_FUNC" or not isinstance(sym["st_shndx"], int):
                    continue
                sec = elf.get_section(sym["st_shndx"])
                movable = (sec.name == f".text.{sym.name}" and sec["sh_addralign"] <= 8
                           and not sec["sh_flags"] & SHF_GROUP)
                out.setdefault(sym.name, (o, sec.name, sec["sh_size"], movable))
    return out


def row_pieces(objs, hot, missing=None, kept_out=None):
    """The row's functions in order: [(object, section)]. The .hot names the
    image doesn't have (inlined or renamed) go to missing, the ones that can't
    move (shared or over-aligned sections) to kept_out."""
    funcs = functions(objs)
    by_base = {}
    for n, v in funcs.items():
        by_base.setdefault(make_otm.clone_base(n), []).append(n)
    pieces, seen = [], set()

    def add(n):
        if n in seen or n not in funcs:
            return
        if not funcs[n][3]:
            if kept_out is not None and n not in kept_out:
                kept_out.append(n)
            return
        seen.add(n)
        pieces.append(funcs[n][:2])

    for name, _ in hot:
        # The bench and the image may split a function differently: every clone.
        names = [name] if name in funcs else by_base.get(make_otm.clone_base(name), [])
        if not names and missing is not None:
            missing.append(name)
        for n in names:
            m = re.match(r"(.*)\.part\.\d+$", n)
            if m and m.group(1) in funcs and m.group(1) not in seen:
                add(m.group(1))   # the split header first: callers enter there
            add(n)
    return pieces


def layout(args):
    lines = ["/* Generated by tools/hot_pool.py layout -- do not edit. */"]
    for name, hotfile, objs in parse_rows(args.row, 3):
        missing, kept_out = [], []
        pieces = row_pieces(objs.split(","), make_otm.read_hot(hotfile), missing, kept_out)
        for what, names in (("not in the image (inlined or renamed)", missing),
                            ("kept in flash (shared or over-aligned)", kept_out)):
            if names:
                print(f"hot_pool: {name}: {len(names)} hot functions {what}: "
                      f"{' '.join(names[:6])}{' ...' if len(names) > 6 else ''}", file=sys.stderr)
        lines.append(f". = ALIGN(8); __hotrow_{name}_start = .;")
        for k, (o, sec) in enumerate(pieces):
            lines.append(f"*/{os.path.basename(os.path.dirname(o))}/{os.path.basename(o)}({sec}) "
                         f". = ALIGN(8); __hotrow_{name}_cut_{k} = .;")
        lines.append(f"__hotrow_{name}_end = .;")
    text = "\n".join(lines) + "\n"
    old = open(args.out).read() if os.path.exists(args.out) else None
    if old != text:
        with open(args.out, "w") as f:
            f.write(text)


