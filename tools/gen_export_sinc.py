#!/usr/bin/env python3
"""Generate the weight table of the 44.1 kHz WAV export conversion.

  gen_export_sinc.py [OUT]          write OUT (default src/core/audio/export_sinc_table.inc)
  gen_export_sinc.py --check [OUT]  exit 1 when OUT differs from a fresh run

The export conversion (src/core/audio/export_resampler.h, spec 04 §6.1)
weights 32 input frames x[n - 15 .. n + 16] per output frame. The weights are
a least-squares fractional-delay design: minimise
int_0^wp |H(w) - e^{-jwD}|^2 dw with wp = 0.82 pi (band edge 0.82 of the
input Nyquist, 18.1 kHz), D = 15 + mu, nothing weighted above wp (eps 0).
The normal equations Q w = p (Q_kl = int_0^wp cos(w (k - l)) dw,
p_k = int_0^wp cos(w (k - D)) dw, 1e-13 added to the diagonal) are solved in
double with a Cholesky factorisation.

The table holds the rows for mu = (row - 1) / 32, rows 0..18: the phases
0..16 of a 32-phase polyphase table plus one margin row on each side for the
Catmull-Rom interpolation between rows. Phases above 1/2 read the row of
1 - mu backwards (the design is symmetric), so these rows are enough. Each
weight is rounded to float32 and printed with 9 significant digits, so the
C++ literal is that float32 exactly.

At mu = 0 the exact design is the identity (weight 1 at x[n], 0 elsewhere:
the delay D = 15 is a whole tap, so H = e^{-jwD} with zero error). The solve
with the diagonal jitter lands within 1.5e-8 of it (off-centre weights of
~1e-8 that survive the float32 rounding); that row is set to the identity
exactly, so output frames at phase 0 copy the input sample.

Python 3 standard library only; the generated file is committed, so ordinary
builds never run this.
"""
import math
import os
import struct
import sys

TAPS = 32
PHASES = 32
ROWS = PHASES // 2 + 3
BAND = 0.82
EPS = 0.0
JITTER = 1e-13

HEADER = ("// GENERATED by tools/gen_export_sinc.py (make export-sinc-table) -- do not edit.\n"
          f"// {TAPS} taps, least squares, band edge {BAND} of Nyquist, eps {EPS:g}, jitter {JITTER:g}; "
          f"rows 0..{ROWS - 1} = mu (row - 1) / {PHASES}; float32.\n")


def cos_int(a, b, d):
    """int_a^b cos(w d) dw."""
    return b - a if abs(d) < 1e-12 else (math.sin(b * d) - math.sin(a * d)) / d


def ls_fd_exact(n, band, eps, mu):
    """The weights of one fractional delay mu (least-squares fractional delay)."""
    c = n // 2 - 1
    wp = band * math.pi
    delay = c + mu
    q = [0.0] * (n * n)
    x = [0.0] * n
    for k in range(n):
        for l in range(n):
            q[k * n + l] = (cos_int(0.0, wp, float(k - l)) + eps * cos_int(wp, math.pi, float(k - l))
                            + (JITTER if k == l else 0.0))
        x[k] = cos_int(0.0, wp, k - delay)
    # Cholesky (Q is symmetric positive definite): Q = L L^T, L in the lower half of q.
    for j in range(n):
        s = q[j * n + j]
        for k in range(j):
            s -= q[j * n + k] * q[j * n + k]
        q[j * n + j] = math.sqrt(s)
        for i in range(j + 1, n):
            t = q[i * n + j]
            for k in range(j):
                t -= q[i * n + k] * q[j * n + k]
            q[i * n + j] = t / q[j * n + j]
    for i in range(n):
        t = x[i]
        for k in range(i):
            t -= q[i * n + k] * x[k]
        x[i] = t / q[i * n + i]
    for i in range(n - 1, -1, -1):
        t = x[i]
        for k in range(i + 1, n):
            t -= q[k * n + i] * x[k]
        x[i] = t / q[i * n + i]
    return x


def f32(v):
    return struct.unpack("f", struct.pack("f", v))[0]


def literal(v):
    """C++ float literal that reads back as the float32 v exactly."""
    s = "%.9g" % v
    if "e" not in s and "." not in s:
        s += ".0"
    assert f32(float(s)) == v, (v, s)
    return s + "f"


def table():
    rows = []
    for r in range(ROWS):
        mu = (r - 1) / PHASES
        if r == 1:
            w = [1.0 if k == TAPS // 2 - 1 else 0.0 for k in range(TAPS)]
        else:
            w = ls_fd_exact(TAPS, BAND, EPS, mu)
        rows.append([f32(v) for v in w])
    return rows


def render(rows):
    out = [HEADER, f"const float kExportSincTable[{ROWS}][{TAPS}] = {{\n"]
    for r, w in enumerate(rows):
        out.append(f"    {{   // row {r}, mu = {r - 1}/{PHASES}\n")
        for k in range(0, TAPS, 4):
            out.append("        " + ", ".join(literal(v) for v in w[k:k + 4]) + ",\n")
        out.append("    },\n")
    out.append("};\n")
    return "".join(out)


def main():
    args = sys.argv[1:]
    check = bool(args) and args[0] == "--check"
    if check:
        args = args[1:]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = args[0] if args else os.path.join(root, "src", "core", "audio", "export_sinc_table.inc")
    text = render(table())
    if check:
        try:
            with open(path) as f:
                same = f.read() == text
        except FileNotFoundError:
            same = False
        print(f"{path}: {'up to date' if same else 'DIFFERS from a fresh run'}")
        return 0 if same else 1
    with open(path, "w") as f:
        f.write(text)
    print(f"wrote {path} ({ROWS} rows x {TAPS} taps, {ROWS * TAPS * 4} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
