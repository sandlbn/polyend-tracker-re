#!/usr/bin/env python3
"""Pack the generated RAM_G font image for the firmware (2.x flash budget).

  pack_fonts.py OUTDIR          write OUTDIR/font_data_z.inc and OUTDIR/font_adv.inc
  pack_fonts.py --check OUTDIR  verify both against OUTDIR/font_data.inc (make host-test)

font_data.inc (gen_fonts.py) is the raw image the simulator and the host tests
use. The firmware stores it zlib-compressed (font_data_z.inc, uploaded with
CMD_INFLATE and CRC-checked after the inflate) plus the pen advances of the ten
fonts (font_adv.inc: the 128-byte width table of each metric block), which is
all the UI reads from the image at run time.
"""
import os
import re
import sys
import zlib

HEADER = ("// GENERATED by tools/fonts/pack_fonts.py from font_data.inc (make fonts) -- do not edit.\n")


def read_raw(out_dir):
    with open(os.path.join(out_dir, "font_data.inc")) as f:
        text = "\n".join(l for l in f.read().splitlines() if not l.lstrip().startswith("//"))
    return bytes(int(x) for x in re.findall(r"\d+", text))


def metric_offsets(out_dir):
    with open(os.path.join(out_dir, "font_data.h")) as f:
        h = f.read()
    m = re.search(r"kFonts\[2\]\[5\] = \{(.*?)\};", h, re.S)
    offs = [int(a) for a in re.findall(r"\{(\d+),\s*\d+,", m.group(1))]
    assert len(offs) == 10, offs
    return offs


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 24):
        rows.append(",".join(str(b) for b in data[i:i + 24]) + ",")
    return "\n".join(rows) + "\n"


def render(out_dir):
    raw = read_raw(out_dir)
    z = zlib.compress(raw, 9)
    assert zlib.decompress(z) == raw
    adv = b"".join(raw[o:o + 128] for o in metric_offsets(out_dir))
    zt = HEADER + "// zlib stream of the RAM_G font image (%d -> %d B, crc32 of the image 0x%08X).\n" % (
        len(raw), len(z), zlib.crc32(raw) & 0xFFFFFFFF) + c_bytes(z)
    at = HEADER + "// Pen advances: kFonts[set][role] metric widths[128], set-major.\n"
    at += "".join("{\n" + c_bytes(adv[i:i + 128]) + "},\n" for i in range(0, len(adv), 128))
    return zt, at


def main():
    args = sys.argv[1:]
    check = args and args[0] == "--check"
    if check:
        args = args[1:]
    if len(args) != 1:
        sys.exit(__doc__)
    out_dir = args[0]
    zt, at = render(out_dir)
    zp, ap = os.path.join(out_dir, "font_data_z.inc"), os.path.join(out_dir, "font_adv.inc")
    if check:
        for path, want in ((zp, zt), (ap, at)):
            with open(path) as f:
                if f.read() != want:
                    sys.exit("pack_fonts: %s is stale (run make fonts)" % path)
        print("pack_fonts: font_data_z.inc / font_adv.inc match font_data.inc")
        return
    with open(zp, "w") as f:
        f.write(zt)
    with open(ap, "w") as f:
        f.write(at)
    print("pack_fonts: %s, %s" % (zp, ap))


if __name__ == "__main__":
    main()
