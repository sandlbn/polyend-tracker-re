const uint8_t kRollInjectValue[5] = {4, 13, 11, 1, 10};

void applyRollSelector(StepFx& inject, uint8_t rollSel, ParkMiller& rng, bool fixCarry) {
    if (rollSel == 0 || rollSel > 15) {  // > 15 never occurs in the tables (OT: treat as 0)
        inject = StepFx{};
        return;
    }
    static const uint8_t kThreshold[3] = {30, 60, 100};
    const int r = rng.range(0, 100);
    const int sel = rollSel - 1;
    if (r < kThreshold[sel % 3]) {
        inject.type = 3;  // Roll (spec 03 §3.5)
        inject.value = kRollInjectValue[sel / 3];
        return;
    }
    if (rollSel == 2 && !fixCarry) return;  // stock quirk: previous roll stays
    inject.type = 0;                         // a miss clears only the type
}

