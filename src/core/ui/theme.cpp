// The named roles read the stock slots (spec 20 §1.4), so every screen that
// still uses them follows the active stock theme. Monochrome is the light
// one: grey 4b4b4b frame, light b9b9ba title band with black title text,
// 3e3e3e panels and c9c9ca list text.
Theme makeTheme(const char* name, const uint32_t* s) {
    Theme t{};
    t.name = name;
    t.bg = s[slot::kFrameClear];             // frame clear colour
    t.text = s[slot::kList + 4];             // list / value text
    t.dim = s[slot::kGrey];                  // 777777 / a8a8a8 / 777777
    t.panel = s[slot::kBottomLabel + 1];     // label background 323132
    t.panel2 = s[slot::kProgress];           // popup background 222222
    t.panelDark = s[slot::kList + 3];        // panel / list background 0a0a0a
    t.accent = s[slot::kFocusFrame];         // focus frame / selection red
    t.alert = s[slot::kEmptyPanel + 2];      // ff0000
    t.good = s[slot::kGreen];
    t.yellow = s[slot::kYellow];
    t.orange = s[slot::kOrange];
    t.cyan = s[slot::kCyan];
    for (int i = 0; i < 4; ++i) {
        t.track[i] = s[slot::kGrid + 2 + i];       // Note / Instr / Fx1 / Fx2 text
        t.trackDark[i] = s[slot::kGrid + 6 + i];   // their empty-cell tints
    }
    t.grid = s[slot::kGridLine];
    t.slots = s;
    return t;
}

const Theme* themes() {
    static const Theme kThemes[kThemeCount] = {
        makeTheme("Original", kOriginalSlots),
        makeTheme("Monochrome", kMonochromeSlots),
        makeTheme("Anniversary", kAnniversarySlots),
    };
    return kThemes;
}
